-- 006: роль «Поставщик», строки товаров в поставках, заказы поставщику.
-- Выполнить один раз: Supabase → SQL Editor → Run. Повторный запуск безопасен.

alter table public.users drop constraint if exists users_role_check;
alter table public.users add constraint users_role_check
  check (role in ('Администратор', 'Кассир', 'Поставщик'));

create table if not exists public.supplier_orders (
    id                  bigint generated by default as identity primary key,
    created_at          timestamptz not null default now(),
    status              text not null default 'отправлен'
                        check (status in ('черновик', 'отправлен', 'подтверждён', 'принят', 'отменён')),
    comment             text,
    created_by_user_id  bigint,
    created_by_name     text,
    confirmed_amount    numeric(14,2),
    confirmed_at        timestamptz,
    confirmed_by_name   text,
    supplier_comment    text,
    accepted_at         timestamptz,
    accepted_by_name    text,
    cancelled_at        timestamptz,
    cancelled_by_name   text,
    ledger_id           bigint references public.supplier_ledger(id) on delete set null
);
create index if not exists supplier_orders_created_idx on public.supplier_orders (created_at desc);

create table if not exists public.supplier_order_lines (
    id          bigint generated by default as identity primary key,
    order_id    bigint not null references public.supplier_orders(id) on delete cascade,
    name        text not null,
    qty         numeric(14,2),
    unit_price  numeric(14,2),
    line_total  numeric(14,2),
    note        text
);
create index if not exists supplier_order_lines_order_idx on public.supplier_order_lines (order_id);

alter table public.supplier_ledger add column if not exists order_id bigint;

create table if not exists public.supplier_ledger_lines (
    id          bigint generated by default as identity primary key,
    ledger_id   bigint not null references public.supplier_ledger(id) on delete cascade,
    name        text not null,
    qty         numeric(14,2),
    unit_price  numeric(14,2),
    line_total  numeric(14,2),
    note        text
);
create index if not exists supplier_ledger_lines_ledger_idx on public.supplier_ledger_lines (ledger_id);

alter table public.supplier_orders       enable row level security;
alter table public.supplier_order_lines  enable row level security;
alter table public.supplier_ledger_lines enable row level security;
grant select, insert, update, delete on public.supplier_orders       to service_role;
grant select, insert, update, delete on public.supplier_order_lines  to service_role;
grant select, insert, update, delete on public.supplier_ledger_lines to service_role;
grant usage, select on all sequences in schema public to service_role;
