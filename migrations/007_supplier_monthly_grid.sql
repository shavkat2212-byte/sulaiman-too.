-- 007: Долг с поставщиком — таблица по месяцам (как Excel)
create table if not exists public.supplier_month_meta (
    year_month      text primary key,            -- '2026-10'
    opening_balance numeric(14,2) not null default 0,
    updated_at      timestamptz not null default now(),
    updated_by_name text
);

create table if not exists public.supplier_day_rows (
    id            bigint generated by default as identity primary key,
    year_month    text not null,
    row_date      date,
    tmz_som       numeric(14,2),
    tmz_usd       numeric(14,2),
    total_goods   numeric(14,2),
    payment       numeric(14,2),
    return_amount numeric(14,2),
    comment       text,
    sort_order    int not null default 0,
    created_at    timestamptz not null default now()
);
create index if not exists supplier_day_rows_month_idx on public.supplier_day_rows (year_month, sort_order);

alter table public.supplier_month_meta enable row level security;
alter table public.supplier_day_rows   enable row level security;
grant select, insert, update, delete on public.supplier_month_meta to service_role;
grant select, insert, update, delete on public.supplier_day_rows   to service_role;
grant usage, select on all sequences in schema public to service_role;

