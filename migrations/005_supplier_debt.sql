-- Магазин «Сулайман-Тоо» — учёт долга с поставщиком (Икром) и «Запомнить меня».
-- Выполнить ОДИН раз: Supabase → SQL Editor → New query → вставить весь файл → Run.
-- Безопасно запускать повторно. Существующие данные не меняются.

-- 1) Операции с поставщиком (только суммы, без фото)
create table if not exists public.supplier_ledger (
    id                  bigint generated by default as identity primary key,
    created_at          timestamptz not null default now(),
    type                text not null check (type in ('товар', 'оплата', 'возврат')),
    amount              numeric(14,2) not null check (amount > 0),
    comment             text,
    created_by_user_id  bigint,
    created_by_name     text,
    created_by_role     text,
    created_by_side     text check (created_by_side in ('магазин', 'поставщик')),
    accepted            boolean not null default false,
    accepted_at         timestamptz,
    accepted_by_user_id bigint,
    accepted_by_name    text
);
create index if not exists supplier_ledger_created_idx on public.supplier_ledger (created_at desc);

-- 2) Токены входа «Запомнить меня» (в базе хранится только хэш токена)
create table if not exists public.user_sessions (
    id          bigint generated by default as identity primary key,
    created_at  timestamptz not null default now(),
    user_id     bigint not null,
    token_hash  text not null unique,
    expires_at  timestamptz not null
);
create index if not exists user_sessions_user_idx on public.user_sessions (user_id);

-- Как и остальные таблицы: RLS включён, политик нет. Приложение ходит ключом service_role,
-- поэтому для него ничего не меняется, а публичный anon-ключ доступа не получит.
-- Supabase с 30.10 требует явных прав для НОВЫХ таблиц — выдаём их service_role:
alter table public.supplier_ledger enable row level security;
alter table public.user_sessions  enable row level security;
grant select, insert, update, delete on public.supplier_ledger to service_role;
grant select, insert, update, delete on public.user_sessions  to service_role;
grant usage, select on all sequences in schema public to service_role;
